"""Builds the retail data files from the game's own tables (DB2), as exported by wago.tools.

    python tools/extract_retail.py <folder with the CSVs> <build>

The folder needs TaxiNodes.csv, TaxiPath.csv, TaxiPathNode.csv, QuestPOIBlob.csv and
QuestPOIPoint.csv for one build, e.g. for 12.1.5.70961:

    https://wago.tools/db2/TaxiNodes/csv?build=12.1.5.70961      (same for the other four)

Writes AtlasRoute/data/retail_taxi.lua and AtlasRoute/data/retail_quests.lua. Nothing in
them is typed by hand: positions are the game's world coordinates (yards; x = Pos_0 / X,
y = Pos_1 / Y, the same axes UnitPosition returns), flight lengths are the lengths of the
flight paths' own waypoints.
"""
import csv
import math
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FLAG_ALLIANCE, FLAG_HORDE, FLAG_SPECIAL = 1, 2, 1024  # TaxiNodes.Flags
NODE_TELEPORT = 1  # TaxiPathNode.Flags: the next waypoint is a jump, not flown
MAX_OBJECTIVES = 26  # QuestPOIBlob.ObjectiveIndex 0..25 are quest log objectives


def rows(folder, table):
    with open(os.path.join(folder, table + ".csv"), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def taxi(folder, build):
    nodes = {}
    for r in rows(folder, "TaxiNodes"):
        flags = int(r["Flags"])
        # Flag 1024 marks scripted rides (quest flights, transports, flavour paths), not
        # flight masters. In game the client's own list (C_TaxiMap) decides what is shown.
        if flags & FLAG_SPECIAL or not flags & (FLAG_ALLIANCE | FLAG_HORDE):
            continue
        nodes[int(r["ID"])] = {
            "name": r["Name_lang"], "continent": int(r["ContinentID"]),
            "x": float(r["Pos_0"]), "y": float(r["Pos_1"]),
            "faction": flags & (FLAG_ALLIANCE | FLAG_HORDE),
        }

    waypoints = defaultdict(list)
    for r in rows(folder, "TaxiPathNode"):
        waypoints[int(r["PathID"])].append(r)

    paths = []
    for r in rows(folder, "TaxiPath"):
        a, b, pid = int(r["FromTaxiNode"]), int(r["ToTaxiNode"]), int(r["ID"])
        if a not in nodes or b not in nodes or a == b:
            continue
        if nodes[a]["continent"] != nodes[b]["continent"]:
            continue
        pts = sorted(waypoints.get(pid, []), key=lambda p: int(p["NodeIndex"]))
        if len(pts) < 2 or len({p["ContinentID"] for p in pts}) > 1:
            continue
        length = 0.0
        for p, q in zip(pts, pts[1:]):
            if int(p["Flags"]) & NODE_TELEPORT:
                continue
            length += math.dist([float(p["Loc_0"]), float(p["Loc_1"]), float(p["Loc_2"])],
                                [float(q["Loc_0"]), float(q["Loc_1"]), float(q["Loc_2"])])
        if length > 0:
            paths.append((a, b, round(length)))
    paths.sort()

    used = {a for a, _, _ in paths} | {b for _, b, _ in paths}
    out = [
        "-- GENERATED by tools/extract_retail.py from the game's DB2 tables (wago.tools), build " + build + ".",
        "-- Do not edit by hand; run the tool again for a new build.",
        "--   nodes[id] = {name, continent, x, y, faction}  (faction: 1 Alliance, 2 Horde, 3 both;",
        "--                x, y = world coordinates in yards, as UnitPosition returns them)",
        "--   paths     = {from, to, yards}  (one-way; yards = length of the flight's waypoints)",
        "local _, ns = ...",
        "ns.RetailTaxi = { build = " + lua_str(build) + ", nodes = {",
    ]
    for i in sorted(used):
        n = nodes[i]
        out.append("  [%d] = { %s, %d, %.1f, %.1f, %d }," % (i, lua_str(n["name"]), n["continent"], n["x"], n["y"], n["faction"]))
    out.append("}, paths = {")
    for a, b, length in paths:
        out.append("  { %d, %d, %d }," % (a, b, length))
    out.append("} }")
    write("retail_taxi.lua", out)
    print("taxi: %d nodes, %d paths" % (len(used), len(paths)))


def centroid(points):
    xs = [float(p["X"]) for p in points]
    ys = [float(p["Y"]) for p in points]
    return sum(xs) / len(xs), sum(ys) / len(ys)


def quests(folder, build):
    points = defaultdict(list)
    for p in rows(folder, "QuestPOIPoint"):
        points[int(p["QuestPOIBlobID"])].append(p)

    # Per quest and objective index (-1 = where the quest is handed in), the blobs the game
    # draws on the map. Unconditional blobs first; a blob with a player condition (faction,
    # phase) is kept only when the quest has no unconditional one for that objective.
    blobs = defaultdict(lambda: defaultdict(list))
    for b in rows(folder, "QuestPOIBlob"):
        bid = int(b["ID"])
        if not points.get(bid):
            continue
        blobs[int(b["QuestID"])][int(b["ObjectiveIndex"])].append(b)

    turnin, objectives = {}, {}
    for q, per in blobs.items():
        for idx, bl in per.items():
            free = [b for b in bl if b["PlayerConditionID"] == "0"] or bl
            free.sort(key=lambda b: int(b["ID"]))
            spots, seen = [], set()
            for b in free:
                x, y = centroid(points[int(b["ID"])])
                key = (int(b["MapID"]), round(x), round(y))
                if key not in seen:
                    seen.add(key)
                    spots.append(key)
            if idx == -1:
                turnin[q] = spots
            elif idx < MAX_OBJECTIVES:
                # 26 and up are not quest log objectives (32, the most common, is where the
                # quest starts: quest 11's index-32 point is its giver, Deputy Rainer, who
                # also takes it back). Quest givers come from the live client instead.
                objectives.setdefault(q, []).append((idx, spots[0]))  # first area per objective

    out = [
        "-- GENERATED by tools/extract_retail.py from the game's DB2 tables (wago.tools), build " + build + ".",
        "-- Where the game's own quest map points are (QuestPOIBlob / QuestPOIPoint).",
        "--   turnin[questID]     = {continent, x, y, continent, x, y, ...}  where it is handed in",
        "--                         (several spots when the game lists several; the planner takes",
        "--                         the one on your continent)",
        "--   objectives[questID] = {index, continent, x, y, ...}  centre of the first map area of",
        "--                         each objective (index 0 = the quest log's first objective)",
        "-- x, y = world coordinates in yards, as UnitPosition returns them.",
        "local _, ns = ...",
        "local T, O = {}, {}",
        "ns.RetailQuests = { build = " + lua_str(build) + ", turnin = T, objectives = O }",
    ]
    entries = ["T[%d]={%s}" % (q, ",".join("%d,%d,%d" % s for s in turnin[q])) for q in sorted(turnin)]
    for q in sorted(objectives):
        entries.append("O[%d]={%s}" % (q, ",".join("%d,%d,%d,%d" % ((i,) + s) for i, s in sorted(objectives[q]))))
    # One function per 1000 entries: Lua caps the constants of a single function.
    for i in range(0, len(entries), 1000):
        out.append("do local function f()")
        out.extend(entries[i:i + 1000])
        out.append("end f() end")
    write("retail_quests.lua", out)
    print("quests: %d turn-ins, %d with objectives" % (len(turnin), len(objectives)))


def write(name, lines):
    path = os.path.join(ROOT, "AtlasRoute", "data", name)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    taxi(sys.argv[1], sys.argv[2])
    quests(sys.argv[1], sys.argv[2])
